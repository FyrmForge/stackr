// put stores plain (already tar or gzip as the object needs) as an encrypted
// archive object under key.
func (w *world) put(t *testing.T, key string, plain []byte) {
	t.Helper()
	var b bytes.Buffer
	enc, err := encrypt(&b, w.dest.ArchiveKey, keyWorkFactor)
	must(t, err)
	_, err = enc.Write(plain)
	must(t, err)
	must(t, enc.Close())
	must(t, open(w.dest).Put(ctx, key, &b))
}

type member struct{ name, body string }

// tgz is a gzipped tar of members, owned by uid 999.
func tgz(t *testing.T, ms ...member) []byte {
	t.Helper()
	var b bytes.Buffer
	gz := gzip.NewWriter(&b)
	tw := tar.NewWriter(gz)
	for _, m := range ms {
		must(t, tw.WriteHeader(&tar.Header{Name: m.name, Mode: 0o600, Size: int64(len(m.body)), Uid: 999, Gid: 999}))
		_, err := tw.Write([]byte(m.body))
		must(t, err)
	}
	must(t, tw.Close())
	must(t, gz.Close())
	return b.Bytes()
}

// untar reads what UntarVolume was given: a gzipped tar, as name -> body.
func untar(t *testing.T, b []byte) map[string]string {
	t.Helper()
	gz, err := gzip.NewReader(bytes.NewReader(b))
	must(t, err)
	tr := tar.NewReader(gz)
	out := map[string]string{}
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return out
		}
		must(t, err)
		body, _ := io.ReadAll(tr)
		out[h.Name] = string(body)
	}
}

// The target volume gets the base as it was, the engine's recovery settings
// appended to its postgresql.auto.conf, an empty recovery.signal, and every
// bundle's WAL files in the restore dir; a bundle that smuggles any other
// name is refused.
func TestFillVolumeLaysBaseWalAndRecoverySettings(t *testing.T) {
	w := setup(t)
	root := bk.PITRRoot("o1", w.vol.ID)
	baseKey := root + "/base/20261107-100000-" + seg1 + "-data.tar.gz.age"
	w.put(t, baseKey, tgz(t,
		member{"PG_VERSION", "17\n"},
		member{"postgresql.auto.conf", "# Do not edit this file manually!\n"},
		member{"standby.signal", ""},
		member{"base/1/1259", "pages"},
	))
	b1, b2 := bk.WALKey(root, seg1, seg2), bk.WALKey(root, seg3, seg3)
	hist := root + "/wal/00000002.history-00000002.history" + bk.BundleExt
	w.put(t, b1, tgz(t, member{seg1, "w1"}, member{seg2, "w2"}))
	w.put(t, b2, tgz(t, member{seg3, "w3"}))
	w.put(t, hist, tgz(t, member{"00000002.history", "1\t0/3000000\tno recovery target specified\n"}))
	plan, err := bk.PickBase(
		[]store.BackupRun{baseRun(baseKey, seg1, seg1)},
		[]string{b1, b2, hist}, bk.Lineage{}, time.Time{}, true)
	must(t, err)

	err = w.f.FillVolume(ctx, Replay{Dest: w.dest, Plan: plan, Target: w.vol, WalDir: "stackr-restore-wal", Conf: "restore_command = 'cp x'\n"}, io.Discard)
	must(t, err)
	got := untar(t, w.fake.Untarred)
	want := map[string]string{
		"PG_VERSION":                          "17\n",
		"postgresql.auto.conf":                "# Do not edit this file manually!\nrestore_command = 'cp x'\n",
		"base/1/1259":                         "pages",
		"recovery.signal":                     "",
		"stackr-restore-wal/":                 "",
		"stackr-restore-wal/" + seg1:          "w1",
		"stackr-restore-wal/" + seg2:          "w2",
		"stackr-restore-wal/" + seg3:          "w3",
		"stackr-restore-wal/00000002.history": "1\t0/3000000\tno recovery target specified\n",
	}
	if len(got) != len(want) {
		t.Errorf("entries = %v", slices.Sorted(keysOf(got)))
	}
	for k, v := range want {
		if g, ok := got[k]; !ok || g != v {
			t.Errorf("%s = %q (present %v), want %q", k, g, ok, v)
		}
	}
	if _, ok := got["standby.signal"]; ok {
		t.Error("the base's standby.signal came along")
	}

	// a bundle holding a path outside the WAL names is refused, nothing is untarred twice
	evil := bk.WALKey(root, seg3, seg3)
	w.put(t, evil, tgz(t, member{"../../etc/passwd", "x"}))
	err = w.f.FillVolume(ctx, Replay{Dest: w.dest, Plan: plan, Target: w.vol, WalDir: "stackr-restore-wal"}, io.Discard)
	if err == nil || !strings.Contains(err.Error(), "not a WAL file") {
		t.Errorf("evil bundle: %v", err)
	}
}

func keysOf[V any](m map[string]V) func(func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

// A base's key names its start segment, and its run row keeps its end.
func TestBaseBackupKeyNamesWalStartAndRowKeepsWalStop(t *testing.T) {
	w := setup(t)
	root := bk.PITRRoot("o1", w.vol.ID)
	w.fake.ExecFn = func(cmd []string) string {
		switch {
		case slices.Contains(cmd, "walstart"):
			return seg1 + "\n"
		case slices.Contains(cmd, "walstop"):
			return seg2 + "\n"
		}
		return string(tarGz(t, "base_backup", "pgdata"))
	}
	sub := Subject{
		Volume: w.vol, Engine: w.api, Base: true, Dump: []string{"pg_basebackup"},
		WalStart: []string{"psql", "walstart"}, WalStop: []string{"psql", "walstop"},
	}
	r, err := w.f.Backup(ctx, sub, Spec{Dest: w.dest, Prefix: root + "/base", Trigger: "manual", PITRDays: 7}, io.Discard)
	must(t, err)
	if bk.BaseWalStart(r.ObjectKey) != seg1 {
		t.Errorf("key %s does not name %s as its start", r.ObjectKey, seg1)
	}
	if r.WalStart == nil || *r.WalStart != seg1 || r.WalStop == nil || *r.WalStop != seg2 {
		t.Errorf("run start/stop = %v / %v", r.WalStart, r.WalStop)
	}
	got, err := w.f.Backups.GetRun(ctx, r.ID)
	must(t, err)
	if got.WalStop == nil || *got.WalStop != seg2 {
		t.Errorf("the stored run lost its wal_stop: %v", got.WalStop)
	}
}

// Pruning leaves an archive alone while a restore holds it, and goes back to
// pruning when the last hold is released.
func TestPruneWindowSkipsAHeldArchive(t *testing.T) {
	w := setup(t)
	root := bk.PITRRoot("o1", w.vol.ID)
	gone := w.oldBase(t, root, 30, seg1)
	w.oldBase(t, root, 20, seg2)
	w.oldBase(t, root, 1, seg3)
	wal := bk.WALKey(root, seg1, seg1)
	must(t, open(w.dest).Put(ctx, wal, strings.NewReader("w")))

	release := w.f.Hold(root)
	release2 := w.f.Hold(root)
	n, err := w.f.PruneWindow(ctx, w.dest, root, 7, time.Now(), io.Discard)
	must(t, err)
	if keys, _ := open(w.dest).List(ctx, root+"/"); n != 0 || !slices.Contains(keys, gone) || !slices.Contains(keys, wal) {
		t.Fatalf("pruned %d while held: %v", n, keys)
	}
	release()
	if n, _ := w.f.PruneWindow(ctx, w.dest, root, 7, time.Now(), io.Discard); n != 0 {
		t.Fatalf("pruned %d with one hold left", n)
	}
	release2()
	if n, err := w.f.PruneWindow(ctx, w.dest, root, 7, time.Now(), io.Discard); err != nil || n == 0 {
		t.Fatalf("pruned %d, %v after the last release", n, err)
	}
	if keys, _ := open(w.dest).List(ctx, root+"/"); slices.Contains(keys, gone) {
		t.Errorf("%s survived once released: %v", gone, keys)
	}
}

// History files are shipped from a restored cluster's own directory and stay there.
func TestShipHistoryLeavesTheFilesInPlace(t *testing.T) {
	w := setup(t)
	w.archive([]string{"00000002.history", seg1, "PG_VERSION"}, "TARBYTES")
	must(t, w.f.ShipHistory(ctx, w.ship(), io.Discard))
	root := bk.PITRRoot("o1", w.vol.ID)
	want := root + "/wal/00000002.history-00000002.history" + bk.BundleExt
	if keys, _ := open(w.dest).List(ctx, root+"/wal/"); !slices.Equal(keys, []string{want}) {
		t.Fatalf("keys = %v", keys)
	}
	for _, c := range w.calls("ExecStream") {
		if c[1] == "rm" {
			t.Errorf("history was removed: %v", c)
		}
	}
}

// A second copy restored from the same source ends on the same timeline; once
// the first one's history is in the archive the second's pre-swap check
// refuses it.
func TestShipHistoryRefusesATimelineTheArchiveHolds(t *testing.T) {
	w := setup(t)
	w.archive([]string{"00000002.history", seg1}, "TARBYTES")
	must(t, w.f.ShipHistory(ctx, w.ship(), io.Discard))
	err := w.f.CheckHistory(ctx, w.ship())
	if _, ok := errs.IsConflict(err); !ok || !strings.Contains(err.Error(), "restore again") {
		t.Fatalf("second ship of timeline 2 = %v; want a conflict", err)
	}
	w.archive([]string{"00000002.history", "00000003.history", seg1}, "TARBYTES")
	if err := w.f.ShipHistory(ctx, w.ship(), io.Discard); err != nil {
		t.Errorf("a copy on a newer timeline was refused: %v", err)
	}
}

// baseRun is a finished base run on key, started at start and ended at stop.
func baseRun(key, start, stop string) store.BackupRun {
	now := time.Now()
	return store.BackupRun{Status: bk.Done, ObjectKey: key, FinishedAt: &now, WalStart: &start, WalStop: &stop}
}

// otherDest is a second destination row over the same storage, standing for
// the destination a base schedule was moved to (or from).
func (w *world) otherDest(t *testing.T) store.BackupDest {
	t.Helper()
	d := w.dest
	d.ID, d.Name = "dest-other", "other"
	must(t, w.st.BackupDests.Create(ctx, d))
	return d
}

// The archive is read, guarded and pruned per destination: a run on one
// destination proves nothing about another, and pruning one never drops the
// other's run rows.
func TestArchiveIsScopedToTheDestination(t *testing.T) {
	w := setup(t)
	root := bk.PITRRoot("o1", w.vol.ID)
	other := w.otherDest(t)
	base := w.oldBase(t, root, 20, seg1) // a run on w.dest

	// Guard: the run on w.dest does not vouch for what sits on `other`
	must(t, open(other).Put(ctx, bk.WALKey(root, seg1, seg1), strings.NewReader("x")))
	if err := w.f.Guard(ctx, other, root); !errors.Is(err, errs.ErrRefused) {
		t.Errorf("a foreign archive on another destination passed: %v", err)
	}
	must(t, w.f.Guard(ctx, w.dest, root))

	// ListArchive: bases of the destination, started after since
	bases, _, _, err := w.f.ListArchive(ctx, w.dest, root, time.Time{})
	must(t, err)
	if len(bases) != 1 || bases[0].ObjectKey != base {
		t.Errorf("bases on the destination = %v", bases)
	}
	if bases, _, _, _ = w.f.ListArchive(ctx, other, root, time.Time{}); len(bases) != 0 {
		t.Errorf("bases on another destination = %v", bases)
	}
	if bases, _, _, _ = w.f.ListArchive(ctx, w.dest, root, time.Now().Add(time.Hour)); len(bases) != 0 {
		t.Errorf("bases from before the epoch = %v", bases)
	}

	// PruneWindow on `other` finds no bases of its own: nothing goes, no row dropped
	w.oldBase(t, root, 30, seg1)
	if n, err := w.f.PruneWindow(ctx, other, root, 7, time.Now(), io.Discard); err != nil || n != 0 {
		t.Errorf("pruned %d (%v) on a destination with no base", n, err)
	}
	if rs, _ := w.f.Backups.Bases(ctx, root, w.dest.ID, time.Time{}); len(rs) != 2 {
		t.Errorf("%d rows left on the destination, want 2", len(rs))
	}
}

// The newest history file gives the lineage: the tip timeline and where each
// ancestor ended.
func TestListArchiveReadsTheLineage(t *testing.T) {
	w := setup(t)
	root := bk.PITRRoot("o1", w.vol.ID)
	_, _, lin, err := w.f.ListArchive(ctx, w.dest, root, time.Time{})
	must(t, err)
	if lin.Tip != "" {
		t.Errorf("tip %q with no history", lin.Tip)
	}
	h2 := root + "/wal/00000002.history-00000003.history" + bk.BundleExt
	w.put(t, h2, tgz(t,
		member{"00000002.history", "1\t0/3000060\tno recovery target\n"},
		member{"00000003.history", "1\t0/3000060\tno recovery target\n2\t0/5000000\tbefore 2026\n"},
	))
	_, _, lin, err = w.f.ListArchive(ctx, w.dest, root, time.Time{})
	must(t, err)
	if lin.Tip != "00000003" || lin.Forks["00000001"] != 3 || lin.Forks["00000002"] != 5 {
		t.Errorf("lineage = %+v", lin)
	}
}

// The promote's preflight lists only: it refuses a held timeline, and ships nothing.
func TestCheckHistoryShipsNothingAndRefusesAHeldTimeline(t *testing.T) {
	w := setup(t)
	w.archive([]string{"00000002.history", seg1}, "TARBYTES")
	root := bk.PITRRoot("o1", w.vol.ID)
	must(t, w.f.CheckHistory(ctx, w.ship()))
	if keys, _ := open(w.dest).List(ctx, root+"/wal/"); len(keys) != 0 {
		t.Fatalf("the check shipped %v", keys)
	}
	must(t, w.f.ShipHistory(ctx, w.ship(), io.Discard))
	if _, ok := errs.IsConflict(w.f.CheckHistory(ctx, w.ship())); !ok {
		t.Error("the check let a held timeline through")
	}
	must(t, w.f.ShipHistory(ctx, w.ship(), io.Discard)) // a resumed promote finds its own upload
}
