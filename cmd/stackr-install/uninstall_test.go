// Only what stackr owns goes: its chains (flushed, then deleted) and the
// rules elsewhere that jump to them, carry its move comment or name its exit
// links. Every other rule, chain and table is untouched.
func TestIptablesPurgeTouchesOnlyStackr(t *testing.T) {
	got := iptablesPurge(cannedSave)
	lines := strings.Split(strings.TrimSpace(got), "\n")

	for _, want := range []string{
		"*raw", "-D PREROUTING -j STACKR-RAW", "-F STACKR-RAW", "-X STACKR-RAW",
		"*mangle", "-D PREROUTING -j STACKR-XM-ab", "-F STACKR-XM-ab", "-X STACKR-XM-ab",
		"*nat", "-D PREROUTING -j STACKR-VIP", "-D POSTROUTING -j STACKR-NAT", "-F STACKR-VIP", "-X STACKR-NAT",
		"*filter", "-D INPUT -i wgx-0123456789 -j DROP",
		"-D INPUT -s 10.207.255.6/32 -p tcp -m tcp --dport 20000:20100 -m comment --comment stackr-move -j ACCEPT",
		"-D DOCKER-USER -j STACKR-FENCE", "-D DOCKER-USER -j STACKR-FWD",
		"-F STACKR-FWD", "-F STACKR-FWD-OWN", "-F STACKR-FENCE", "-X STACKR-FWD-OWN", "-X STACKR-FENCE",
	} {
		if !contains(lines, want) {
			t.Errorf("payload lacks %q:\n%s", want, got)
		}
	}
	for _, l := range lines {
		switch {
		case strings.HasPrefix(l, "*"), l == "COMMIT":
		case strings.HasPrefix(l, "-F "), strings.HasPrefix(l, "-X "):
			if !strings.HasPrefix(l[3:], "STACKR-") {
				t.Errorf("flushes or deletes a chain that is not stackr's: %q", l)
			}
		case strings.HasPrefix(l, "-D "):
			if !strings.Contains(l, "STACKR-") && !strings.Contains(l, "stackr-move") && !strings.Contains(l, "wgx-") {
				t.Errorf("deletes a rule that is not stackr's: %q", l)
			}
		default:
			t.Errorf("unexpected line %q", l)
		}
	}
	for _, kept := range []string{"203.0.113.9", "dport 22 ", "MASQUERADE", "192.168.1.0/24", "RETURN", "DOCKER", "docker0", "FORWARD"} {
		for _, l := range lines {
			if strings.HasPrefix(l, "-D ") && strings.Contains(l, kept) && !strings.Contains(l, "STACKR-") {
				t.Errorf("touches %q: %q", kept, l)
			}
		}
	}
	// A box with nothing of stackr's has nothing to do.
	if p := iptablesPurge("*filter\n:INPUT ACCEPT [0:0]\n-A INPUT -p tcp -j ACCEPT\nCOMMIT\n"); strings.TrimSpace(p) != "" {
		t.Errorf("payload for a clean box = %q", p)
	}
}

// flat joins the runner's wrapped lines (it breaks before every flag).
func flat(s string) string {
	return strings.Join(strings.Fields(strings.ReplaceAll(s, "\\\n", " ")), " ")
}

func contains(lines []string, s string) bool {
	for _, l := range lines {
		if l == s {
			return true
		}
	}
	return false
}

// uninstallRig is a worker box on disk and a reader answering the host's
// docker and ip queries.
type uninstallRig struct {
	state, install string
	out            strings.Builder
	reads          map[string]string
}

func newUninstallRig(t *testing.T) *uninstallRig {
	t.Helper()
	r := &uninstallRig{state: t.TempDir(), install: t.TempDir(), reads: map[string]string{
		"docker ps -aq --filter label=stackr.managed=true":                  "c1\nc2\n",
		"docker ps -aq --filter name=^buildx_buildkit_stackr-builder":       "b1\n",
		"docker volume ls -q --filter name=^buildx_buildkit_stackr-builder": "b1_state\n",
		"docker network ls -q --filter label=stackr.managed=true":           "n1\n",
		"docker volume ls -q --filter label=stackr.managed=true":            "v1\nv2\n",
		"docker image ls -q --filter label=stackr.managed=true":             "i1\n",
		"docker image ls -q --filter reference=ghcr.io/fyrmforge/stackr":    "i2\n",
		"docker image ls --format {{.Repository}} {{.ID}}": "localhost:5000/stackr.system/stackr i3\nlocalhost:5000/stackr.system/tools/rsync i4\n" +
			"localhost:5000/acme/docker.io/library/nginx i5\nghcr.io/fyrmforge/stackr i2\npostgres i9\n",
		"iptables-save": cannedSave,
	}}
	mesh := `{"Links":[{"Iface":"wgx-aaaaaaaaaa","Table":1001}],"Serves":[{"Iface":"wgx-bbbbbbbbbb","Table":1301,"Pref":20002}],` +
		`"Ladders":[{"Subject":{"Sources":["10.208.1.0/24"],"PrefBase":10000}}]}`
	for name, body := range map[string]string{"mesh.json": mesh, "node.name": "h3\n"} {
		if err := os.WriteFile(filepath.Join(r.state, name), []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return r
}

func (r *uninstallRig) env(dry bool, stdin string) uninstallEnv {
	return uninstallEnv{
		r: runner{dry: dry, out: &r.out}, stateDir: r.state, installDir: r.install, in: strings.NewReader(stdin),
		read: func(_ context.Context, name string, args ...string) (string, error) {
			v, ok := r.reads[strings.Join(append([]string{name}, args...), " ")]
			if !ok {
				return "", errors.New("unexpected read " + name + " " + strings.Join(args, " "))
			}
			return v, nil
		},
	}
}

func index(t *testing.T, s, sub string, after int) int {
	t.Helper()
	i := strings.Index(s[after:], sub)
	if i < 0 {
		t.Fatalf("no %q after offset %d in:\n%s", sub, after, s)
	}
	return after + i
}

// The plan, in order: stop the service first so nothing is re-made, then
// containers, networks, firewall, then the links and tables of the mesh.
// Volumes and images stay.
func TestUninstallCommands(t *testing.T) {
	r := newUninstallRig(t)
	if err := r.env(true, "").run(context.Background(), false); err != nil {
		t.Fatal(err)
	}
	out := flat(r.out.String())
	at := 0
	for _, step := range []string{
		"systemctl disable --now stackr-worker.service",
		"rm -f " + joinUnitPath,
		"systemctl daemon-reload",
		"docker rm -f c1 c2",
		"docker rm -f stackr-proxy stackr-host-helper",
		"docker rm -f b1",
		"docker network rm n1",
		"iptables-restore --noflush",
		"-D DOCKER-USER -j STACKR-FENCE",
		"ip link del stackr0",
		"ip link del wgx-aaaaaaaaaa",
		"ip link del wgx-bbbbbbbbbb",
		"ip route flush table 1001",
		"ip route flush table 1301",
		"ip rule del pref 20002",
		"ip rule del pref 10000",
		"ip rule del pref 10001",
	} {
		at = index(t, out, step, at)
	}
	for _, kept := range []string{"volume rm", "image rm", "rm -rf", "/usr/local/bin/"} {
		if strings.Contains(out, kept) {
			t.Errorf("a plain uninstall ran %q:\n%s", kept, out)
		}
	}
}

// A mesh.json is only a file on the box: whatever it names outside stackr's
// own interfaces, route tables and rule priorities is skipped, never run.
func TestUninstallMeshStaysInStackrRanges(t *testing.T) {
	r := newUninstallRig(t)
	bad := `{"Links":[{"Iface":"eth0","Table":254},{"Iface":"wgx-a; reboot","Table":1001}],` +
		`"Serves":[{"Iface":"docker0","Table":0,"Pref":0},{"Iface":"wg0","Table":1301,"Pref":32766}],` +
		`"Ladders":[{"Subject":{"Sources":["10.208.1.0/24"],"PrefBase":0}}]}`
	if err := os.WriteFile(filepath.Join(r.state, "mesh.json"), []byte(bad), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := r.env(true, "").run(context.Background(), false); err != nil {
		t.Fatal(err)
	}
	out := flat(r.out.String())
	for _, no := range []string{"ip link del eth0", "ip link del docker0", "ip link del wg0", "ip link del wgx-a", "flush table 254", "flush table 0", "del pref 0", "del pref 1 ", "del pref 32766"} {
		if strings.Contains(out, no) {
			t.Errorf("uninstall ran %q from a hostile mesh.json:\n%s", no, out)
		}
	}
	for _, yes := range []string{"ip link del stackr0", "ip route flush table 1001", "ip route flush table 1301", "skipping"} {
		if !strings.Contains(out, yes) {
			t.Errorf("missing %q:\n%s", yes, out)
		}
	}
}

// --purge also takes the volumes, the images and the state, but only after
// the node's name is typed; --yes does not stand in for it.
func TestUninstallPurgeAsksTheName(t *testing.T) {
	ctx := context.Background()
	r := newUninstallRig(t)
	err := r.env(true, "h9\n").run(ctx, true)
	if err == nil || !strings.Contains(err.Error(), "name") {
		t.Fatalf("a wrong name = %v", err)
	}
	if strings.Contains(r.out.String(), "would run") {
		t.Fatalf("something ran before the name was confirmed:\n%s", r.out.String())
	}

	r = newUninstallRig(t)
	e := r.env(true, "")
	e.yes = true
	if err := e.run(ctx, true); err == nil {
		t.Fatal("--yes skipped the purge prompt")
	}

	r = newUninstallRig(t)
	if err := r.env(true, "h3\n").run(ctx, true); err != nil {
		t.Fatal(err)
	}
	out := r.out.String()
	for _, want := range []string{"docker volume rm v1 v2", "docker volume rm stackr-caddy", "docker volume rm b1_state", "docker image rm -f i1 i2 i3 i4 i5", "rm -rf " + r.state,
		"rm -f /usr/local/bin/.stackr-swap /usr/local/bin/stackrd /usr/local/bin/stackrd.prev /usr/local/bin/stackr-install /usr/local/bin/stackr-install.prev"} {
		if !strings.Contains(flat(out), want) {
			t.Errorf("purge lacks %q:\n%s", want, out)
		}
	}
	if strings.Contains(out, "i9") {
		t.Errorf("purge removed an image stackr did not pull:\n%s", out)
	}
}

// A box that joined before node.name existed is asked for the node id in its
// cert's CN.
func TestUninstallPurgeFallsBackToTheCertID(t *testing.T) {
	r := newUninstallRig(t)
	if err := os.Remove(filepath.Join(r.state, "node.name")); err != nil {
		t.Fatal(err)
	}
	key, _ := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	tpl := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "node-4711"},
		NotBefore: time.Now(), NotAfter: time.Now().Add(time.Hour)}
	der, err := x509.CreateCertificate(rand.Reader, tpl, tpl, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	crt := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})
	if err := os.WriteFile(filepath.Join(r.state, "node.crt"), crt, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := r.env(true, "h3\n").run(context.Background(), true); err == nil {
		t.Fatal("the old name was accepted without node.name")
	}
	r = newUninstallRig(t)
	_ = os.Remove(filepath.Join(r.state, "node.name"))
	_ = os.WriteFile(filepath.Join(r.state, "node.crt"), crt, 0o644)
	if err := r.env(true, "node-4711\n").run(context.Background(), true); err != nil {
		t.Fatalf("the cert id was refused: %v", err)
	}
}

// A controller keeps its panel: uninstall is for workers.
func TestUninstallRefusesAController(t *testing.T) {
	r := newUninstallRig(t)
	if err := os.WriteFile(filepath.Join(r.install, "install.json"), []byte("{}"), 0o600); err != nil {
		t.Fatal(err)
	}
	for _, f := range []string{"node.name", "mesh.json"} {
		_ = os.Remove(filepath.Join(r.state, f))
	}
	err := r.env(true, "").run(context.Background(), false)
	if err == nil || !strings.Contains(err.Error(), "runs the panel") {
		t.Fatalf("controller uninstall = %v", err)
	}
	if strings.Contains(r.out.String(), "would run") {
		t.Fatal("something ran on a controller")
	}
}

// The state dir that purge removes must be a real directory, never /.
func TestUninstallRefusesOddStateDirs(t *testing.T) {
	for _, d := range []string{"/", "", "relative/dir", "/var"} {
		r := newUninstallRig(t)
		e := r.env(true, "h3\n")
		e.stateDir = d
		if err := e.run(context.Background(), true); err == nil {
			t.Errorf("state dir %q accepted", d)
		}
	}
}
